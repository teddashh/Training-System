import {expect,type Page} from '@playwright/test';
import {rowMenu,trainingMore} from './navigation';
import {readFileSync} from 'node:fs';
const covers=JSON.parse(readFileSync(new URL('../../shared/brand/covers.json',import.meta.url),'utf8')) as {id:string;title:string;category:string}[];
const url=(path:string)=>(process.env.E2E_SUBPATH||'')+path;
export async function libraryWorkflow(page:Page) {
  const csrf=(await page.context().cookies()).find(c=>/^(?:__Host-)?training_csrf$/.test(c.name))!.value;
  const headers={'X-CSRFToken':csrf};const title=`Library workflow ${Date.now()}`;
  const response=await page.request.post(url('/api/courses/'),{headers,data:{title,cover:'microsoft-teams',blocks:[{type:'text',text:'A lesson with a separate assessment.'}]}});
  expect(response.status()).toBe(201);const course=await response.json();
  const quiz=await (await page.request.post(url('/api/exams/'),{headers,data:{title:`Quiz ${title}`,published:true,questions:[{type:'single',description:'Which option is correct?',options:['Correct','Incorrect'],solution:[0],points:100,position:0}]}})).json();
  expect(quiz.id).toBeTruthy();
  await page.goto(url('/courses'));
  let card=page.locator('.course-card').filter({has:page.getByRole('heading',{name:title,exact:true})});
  await expect(card).toHaveCount(0);
  await page.goto(url('/authoring'));
  const draft=page.locator('.training-row').filter({hasText:title});
  await rowMenu(page,title);
  await expect(draft.getByRole('button',{name:'Publish course',exact:true})).toBeVisible();
  await expect(draft.getByRole('link',{name:'Assign training',exact:true})).toHaveCount(0);
  await draft.getByRole('button',{name:'Course settings',exact:true}).click();
  const preview=page.locator('.course-cover-field .course-cover');
  await expect(preview.locator('.course-cover-image')).toHaveAttribute('src',url('/covers/microsoft-teams.svg?v=2'));
  const originalBackground=await preview.locator('.course-cover-image').getAttribute('src');
  const updatedTitle=`Updated ${title}`;
  await page.getByLabel('Course title',{exact:true}).fill(updatedTitle);
  await expect(preview.locator('.course-cover-title')).toHaveText(updatedTitle);
  await expect(preview.locator('.course-cover-image')).toHaveAttribute('src',originalBackground!);
  await page.getByRole('button',{name:'Choose cover',exact:true}).click();
  const picker=page.getByRole('dialog',{name:'Choose cover',exact:true});
  await expect(picker.locator('.cover-library-grid > button')).toHaveCount(covers.filter(c=>c.id.startsWith('scene-')).length);
  await picker.getByLabel('Cover theme',{exact:true}).selectOption('Patterns');
  await expect(picker.locator('.cover-library-grid > button')).toHaveCount(100);
  await picker.getByLabel('Cover theme',{exact:true}).selectOption('');
  await picker.getByLabel('Search covers',{exact:true}).fill('堆高機');
  await expect(picker.getByRole('button',{name:'Forklift crossing',exact:true})).toBeVisible();
  await expect(picker.locator('.cover-library-grid > button')).toHaveCount(1);
  await picker.getByLabel('Search covers',{exact:true}).fill('Orbit 01');
  await expect(picker.locator('.cover-library-grid > button')).toHaveCount(1);
  await picker.getByLabel('Search covers',{exact:true}).fill('');
  const selectedCover=covers.find(c=>c.id==='scene-plant-skyline')!;
  await picker.getByLabel('Cover theme',{exact:true}).selectOption(selectedCover.category);
  await expect(picker.locator('.cover-library-grid > button')).toHaveCount(6);
  await picker.getByRole('button',{name:selectedCover.title,exact:true}).click();
  await expect(preview.locator('.course-cover-image')).toHaveAttribute('src',url('/covers/scene-plant-skyline.svg?v=2'));
  await expect(preview.locator('.course-cover-title')).toHaveText(updatedTitle);
  await expect(preview.locator('.course-cover-logo')).toBeVisible();
  await page.getByRole('button',{name:'Create quiz',exact:true}).click();
  const quizEditor=page.getByRole('dialog',{name:'Create exam',exact:true});
  await expect(quizEditor.locator('.linked-course-chips')).toContainText(title);
  await expect(quizEditor.getByRole('combobox',{name:'Add course',exact:true})).toHaveValue('');
  await quizEditor.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByLabel('Existing quiz',{exact:true}).selectOption(String(quiz.id));
  await page.getByRole('button',{name:'Attach quiz',exact:true}).click();
  await expect(page.locator('.assessment-link').getByText(quiz.title,{exact:true})).toBeVisible();
  await page.getByRole('dialog',{name:'Edit course details',exact:true}).getByRole('button',{name:'Publish course',exact:true}).click();
  await page.goto(url('/courses'));
  card=page.locator('.course-card').filter({has:page.getByRole('heading',{name:updatedTitle,exact:true})});
  await expect(card.getByText('Published',{exact:true})).toBeVisible();
  await page.reload();
  await expect(card.locator('.course-cover-image')).toHaveAttribute('src',url('/covers/scene-plant-skyline.svg?v=2'));
  await expect(card.locator('.course-cover').getByRole('heading',{name:updatedTitle,exact:true})).toBeVisible();
  await expect(card.locator('.course-cover').getByRole('heading')).toHaveCount(1);
  await expect(card.locator('.course-cover-logo')).toBeVisible();
  await expect(card.locator('.course-assessment-block').getByText('Published',{exact:true})).toHaveCount(0);
  await expect(card.getByRole('link',{name:'Preview exam',exact:true})).toHaveCount(0);
  await expect(card.getByRole('link',{name:'Take assessment',exact:true})).toHaveAttribute('href',url(`/exams?exam=${quiz.id}&action=start`));
  await card.getByRole('button',{name:'Manage quizzes',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Edit course details',exact:true})).toBeVisible();
  await page.getByRole('dialog',{name:'Edit course details',exact:true}).getByRole('button',{name:'Close',exact:true}).first().click();
  await card.getByRole('link',{name:'Take assessment',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Ready to start?',exact:true}).getByRole('heading',{name:quiz.title,exact:true})).toBeVisible();

  const {default:JSZip}=await import('../../vendor/scormly/node_modules/jszip/lib/index.js');const zip=new JSZip();
  zip.file('ppt/presentation.xml','<p:presentation xmlns:p="urn:presentation" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><p:sldIdLst><p:sldId r:id="r2"/><p:sldId r:id="r1"/></p:sldIdLst></p:presentation>');
  zip.file('ppt/_rels/presentation.xml.rels','<Relationships><Relationship Id="r1" Target="slides/slide1.xml"/><Relationship Id="r2" Target="slides/slide2.xml"/></Relationships>');
  for(const [n,text] of [[1,'Second lesson from slides'],[2,'First lesson from slides']] as const)zip.file(`ppt/slides/slide${n}.xml`,`<slide xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"><a:p><a:r><a:t>${text}</a:t></a:r></a:p></slide>`);
  await page.goto(url('/authoring'));await trainingMore(page,'Create course');
  await page.getByRole('radio',{name:'PDF / PowerPoint',exact:true}).check();
  await page.getByLabel('Document',{exact:true}).setInputFiles({name:'Imported training.pptx',mimeType:'application/vnd.openxmlformats-officedocument.presentationml.presentation',buffer:await zip.generateAsync({type:'nodebuffer'})});
  await expect(page.getByText('2 lessons ready to edit',{exact:true})).toBeVisible();
  await page.getByLabel('Course title',{exact:true}).fill(`Document ${title}`);
  await page.getByRole('button',{name:'Create and edit',exact:true}).click();
  await expect(page.getByLabel('Content title',{exact:true})).toHaveValue(`Document ${title}`);
  const id=new URL(page.url()).searchParams.get('course');expect(id).toBeTruthy();
  const imported=await (await page.request.get(url(`/api/courses/${id}/`))).json();
  expect(imported.cover).toBe('scene-learning-classroom');
  expect(imported.published).toBe(false);expect(imported.blocks.map((b:{text:string})=>b.text)).toEqual(['Page 1','First lesson from slides','Page 2','Second lesson from slides']);
  await expect(page.getByText('Page 1',{exact:true}).first()).toBeVisible();
  await expect(page.getByText('Page 2',{exact:true}).first()).toBeVisible();
  await expect(page.locator('[contenteditable="true"]').filter({hasText:'First lesson from slides'}).first()).toBeVisible();
}
